def digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def as_bytes(content: str) -> bytes:
    return content.encode("utf-8")


def source_provenance(slug: str) -> str:
    if slug in {"data-quality-guardian", "incident-response-squad"}:
        return "https://github.com/gutomec/nirvana-squads-free — commit 6134bf9 (2026-06-25), cópia em 2026-09-16."
    if slug in {"apex-context-supreme", "genius-athena-strange"}:
        return "https://github.com/marciobisognin/Squads-Genius — commit 34f431d (2026-07-20), cópia em 2026-09-16."
