def build_skill(source_root: Path, slug: str, spec: dict) -> dict[str, bytes]:
    source = source_root / slug
    if not source.is_dir() or source.is_symlink():
        raise ValueError(f"Origem ausente ou link simbólico: {source}")
    files: dict[str, bytes] = {}
    inventory = []
    for path in sorted(source.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"Link simbólico não permitido: {path}")
        if path.is_file():
            relative = path.relative_to(source).as_posix()
            data = path.read_bytes()
            files[f"references/squad/{relative}"] = data
            inventory.append({"path": relative, "bytes": len(data), "sha256": digest(data)})
    squad = yaml.safe_load(files["references/squad/squad.yaml"].decode("utf-8-sig"))
    if squad["name"] != slug:
        raise ValueError(f"Slug incompatível: {slug} != {squad['name']}")
    components = squad.get("components", {})
    author = squad.get("author") or "Não informado no pacote original"
    license_id = squad.get("license") or "LicenseRef-Unspecified"
    expected_license = {"landing-funnel": "Commercial", "instagram-caption-writer": "LicenseRef-Unspecified"}.get(slug, "MIT")
    if license_id != expected_license:
        raise ValueError(f"Licença mudou em {slug}; revisar a adaptação antes de importar")
    if len(spec["description"]) > 200:
        raise ValueError(f"Descrição longa: {slug}")
    referenced = [("Manifesto original e contratos", "squad.yaml"), ("Ponto de entrada", spec["entry"]), ("Workflow principal", spec["workflow"])] + spec["refs"]
    for _, ref in referenced:
        if f"references/squad/{ref}" not in files:
            raise ValueError(f"Referência inexistente em {slug}: {ref}")
    # Validate all wrapper paths written in the domain-specific guidance.
    guidance = "\n".join(spec["steps"]) + spec["pitfalls"]
    for ref in re.findall(r"`((?:tasks|agents|workflows|templates|checklists|data)/[^`]+\.(?:md|yaml))`", guidance):
        if f"references/squad/{ref}" not in files:
            raise ValueError(f"Referência de procedimento inexistente em {slug}: {ref}")
    missing = []
    for kind in ("agents", "tasks", "workflows", "checklists", "templates", "scripts", "commands"):
        for item in components.get(kind, []):
            if not isinstance(item, str):
                continue
