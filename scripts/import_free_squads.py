def safe_file(root: Path, relative: str) -> Path:
    path = root / relative
    if path.is_symlink() or not path.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"Destino fora da pasta gerenciada: {path}")
    return path


def preflight(destination: Path, files: dict[str, bytes]) -> set[str]:
    if destination.is_symlink():
        raise ValueError(f"Destino é link simbólico: {destination}")
    marker_path = destination / ".clariflix-import.json"
    prior: set[str] = set()
    if destination.exists():
        if not marker_path.is_file():
            raise ValueError(f"Recusando sobrescrever destino não gerenciado: {destination}")
        previous = json.loads(marker_path.read_text(encoding="utf-8"))
        if previous.get("managed_by") != MANAGED_BY:
            raise ValueError(f"Destino pertence a outro importador: {destination}")
        prior = set(previous["files"])
        for relative in prior:
            safe_file(destination, relative)
        actual = {path.relative_to(destination).as_posix() for path in destination.rglob("*") if path.is_file()}
        unknown = actual - prior - {".clariflix-import.json"}
        if unknown:
            raise ValueError(f"Arquivos não gerenciados em {destination}: {sorted(unknown)}")
    for relative in files:
        safe_file(destination, relative)
    return prior


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--output-root", type=Path, default=Path(__file__).resolve().parents[1] / "skills")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source_root = args.source_root.resolve()
    if (source_root / "squads-gratuitos").is_dir():
        source_root = source_root / "squads-gratuitos"
    output_root = args.output_root.resolve()
    plans = []
    # All validation happens before the first filesystem mutation.
    for slug, spec in SPECS.items():
        files = build_skill(source_root, slug, spec)
        destination = output_root / slug
        prior = preflight(destination, files)
        marker = {"managed_by": MANAGED_BY, "version": VERSION, "files": {name: digest(content) for name, content in sorted(files.items())}}
        files[".clariflix-import.json"] = as_bytes(json.dumps(marker, ensure_ascii=False, indent=2) + "\n")
        plans.append((destination, files, prior))
    differences = []
    for destination, files, prior in plans:
        for relative, content in files.items():
            path = safe_file(destination, relative)
            if args.check:
                if not path.is_file() or path.read_bytes() != content:
                    differences.append(f"{destination.name}/{relative}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                if not path.exists() or path.read_bytes() != content:
                    path.write_bytes(content)
        for relative in prior - set(files):
            path = safe_file(destination, relative)
            if args.check:
                differences.append(f"arquivo obsoleto: {destination.name}/{relative}")
            elif path.is_file():
                path.unlink()
    if differences:
        print("Divergências de reprodução:\n" + "\n".join(differences), file=sys.stderr)
        return 1
    if not args.check:
        for destination, files, _ in plans:
            for relative, content in files.items():
                if safe_file(destination, relative).read_bytes() != content:
                    raise ValueError(f"Falha de integridade após escrita: {destination}/{relative}")
    count = sum(sum(name.startswith("references/squad/") for name in files) for _, files, _ in plans)
    print(f"{len(plans)} skills {'verificadas' if args.check else 'importadas'}; {count} arquivos originais preservados e verificados.")
    return 0


